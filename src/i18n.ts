export const translations: Record<Lang, Record<string, string>> = { en, fr, de, es };

export function detectBrowserLang(): Lang {
  try {
    const nav: any = typeof navigator !== 'undefined' ? navigator : null;
    const cands: string[] = (nav && nav.languages && nav.languages.length ? nav.languages : (nav ? [nav.language] : [])) || [];
    for (const c of cands) {
      const code = String(c).slice(0, 2).toLowerCase();
      if ((SUPPORTED_LANGS as string[]).includes(code)) return code as Lang;
    }
  } catch (e) { /* no navigator (SSR/tests) */ }
  return 'en';
}

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let s = translations[lang]?.[key] ?? translations.en[key] ?? key;
  if (vars) for (const k of Object.keys(vars)) s = s.split('{' + k + '}').join(String(vars[k]));
  return s;
}
